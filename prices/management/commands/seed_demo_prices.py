from __future__ import annotations

import hashlib
import json
from datetime import date, timedelta
from decimal import Decimal

from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from django.utils import timezone

from prices.models import (
    AuditEvent,
    ImportBatch,
    PriceObservation,
    PriceSeries,
    Source,
    VerificationEvent,
)

DEMO_END_DATE = date(2026, 8, 17)
SEASONAL_PATTERN = (
    Decimal("-0.42"),
    Decimal("-0.25"),
    Decimal("0.08"),
    Decimal("0.31"),
    Decimal("0.48"),
    Decimal("0.29"),
    Decimal("0.02"),
    Decimal("-0.18"),
    Decimal("-0.36"),
    Decimal("-0.12"),
    Decimal("0.21"),
    Decimal("0.39"),
    Decimal("0.14"),
)


class Command(BaseCommand):
    help = "Create an idempotent, deterministic 104-week M'lang demonstration series."

    def add_arguments(self, parser):
        parser.add_argument(
            "--end-date",
            default=DEMO_END_DATE.isoformat(),
            help="Final ISO-week Monday (default: 2026-08-17).",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        try:
            end_date = date.fromisoformat(options["end_date"])
        except ValueError as exc:
            raise CommandError("--end-date must use YYYY-MM-DD.") from exc
        if end_date.weekday() != 0:
            raise CommandError("--end-date must be a Monday so all fixture dates are unambiguous.")
        if end_date > timezone.localdate():
            raise CommandError("--end-date cannot be in the future.")

        source, _ = Source.objects.get_or_create(
            slug="gabay-synthetic-demo",
            defaults={
                "name": "GABAY deterministic demonstration fixture",
                "source_type": Source.Type.DEMONSTRATION,
                "scope": Source.Scope.DEMO,
                "location_name": "M'lang, Cotabato",
                "citation": "Synthetic thesis demonstration fixture generated by GABAY.",
                "publication_allowed": True,
                "metadata": {"generator": "seed_demo_prices", "version": 1},
            },
        )
        series, _ = PriceSeries.objects.get_or_create(
            slug="demo-mlang-palay-other-dry",
            defaults={
                "name": "DEMO M'lang dry palay (other variety)",
                "location_name": "M'lang, Cotabato",
                "location_code": "MLANG",
                "location_level": PriceSeries.LocationLevel.MUNICIPALITY,
                "classification": PriceSeries.Classification.OTHER,
                "condition": PriceSeries.Condition.DRY,
                "moisture_basis": Decimal("14.00"),
                "scope": PriceSeries.Scope.DEMO,
                "is_primary_public": True,
            },
        )
        if not PriceSeries.objects.filter(
            scope=PriceSeries.Scope.DEMO, is_primary_public=True
        ).exists():
            series.is_primary_public = True
            series.save(update_fields=["is_primary_public"])

        points = []
        first_date = end_date - timedelta(weeks=103)
        for index in range(104):
            observed_on = first_date + timedelta(weeks=index)
            trend = Decimal(index) * Decimal("0.018")
            seasonal = SEASONAL_PATTERN[index % len(SEASONAL_PATTERN)]
            slow_cycle = Decimal(((index // 13) % 4) - 1) * Decimal("0.11")
            price = (Decimal("17.50") + trend + seasonal + slow_cycle).quantize(
                Decimal("0.01")
            )
            points.append({"date": observed_on.isoformat(), "price": str(price)})

        payload = {
            "fixture": "GABAY_DEMO_104_WEEK_V1",
            "disclaimer": "Demonstration data—not verified market information.",
            "points": points,
        }
        checksum = hashlib.sha256(
            json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
        ).hexdigest()
        batch, _ = ImportBatch.objects.get_or_create(
            kind=ImportBatch.Kind.DEMO,
            series=series,
            source=source,
            checksum_sha256=checksum,
            defaults={
                "status": ImportBatch.Status.APPROVED,
                "original_filename": "GABAY_DEMO_104_WEEK_V1",
                "source_payload": payload,
                "total_rows": 104,
                "valid_rows": 104,
                "approved_rows": 104,
                "validated_at": timezone.now(),
                "completed_at": timezone.now(),
            },
        )

        created = 0
        verified_at = timezone.now()
        for point in points:
            observed_on = date.fromisoformat(point["date"])
            reference = f"GABAY_DEMO_104_WEEK_V1:{point['date']}"
            if PriceObservation.objects.filter(
                series=series,
                source=source,
                observed_on=observed_on,
                source_reference=reference,
            ).exists():
                continue
            observation = PriceObservation.objects.create(
                series=series,
                source=source,
                import_batch=batch,
                observed_on=observed_on,
                normalized_price=Decimal(point["price"]),
                original_price=Decimal(point["price"]),
                original_unit="PHP/kg",
                source_reference=reference,
                collection_method="Deterministic synthetic generator",
                notes="Demonstration data—not verified market information.",
                workflow_status=PriceObservation.Status.VERIFIED,
                verified_at=verified_at,
            )
            VerificationEvent.objects.create(
                observation=observation,
                action=VerificationEvent.Action.APPROVED,
                from_status=PriceObservation.Status.PENDING,
                to_status=PriceObservation.Status.VERIFIED,
                reason="System-created demonstration fixture; not real market evidence.",
            )
            created += 1

        AuditEvent.objects.create(
            action="demo_fixture.seeded",
            entity_type=batch._meta.label,
            entity_id=str(batch.public_id),
            details={"created": created, "expected": 104, "checksum": checksum},
        )
        self.stdout.write(
            self.style.SUCCESS(
                f"Demo fixture ready: 104 weeks ({created} newly created). "
                "DEMONSTRATION DATA ONLY."
            )
        )
